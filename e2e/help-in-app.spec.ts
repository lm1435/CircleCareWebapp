import { existsSync, readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { test, expect } from './fixtures';
import { checkA11y } from './helpers';

// IN-APP HELP WITH VIDEOS (docs/plans/in-app-help.md, 1.3.0).
//
// Path covered, signed in: open Help from the account menu -> search -> open an
// article -> the <video> carries the right source / poster / muted autoplay
// attributes -> a related article opens in-app. Also: the contextual
// "How does this work?" link, the "video unavailable" failure state, and the
// signed-out entry from /login. Axe runs on the hub and an article.
//
// Content comes from the bundled src/help/content.json (generated by the other
// agent / the CircleCareWeb export). The expectations are derived from it, not
// hard-coded, so a copy edit does not break this spec; with no content.json the
// whole file is skipped rather than failing.
//
// The Supabase Storage bucket is NOT seeded in a plain local stack, so video
// requests are intercepted: held (element stays on screen) for the attribute
// checks, aborted for the failure-state check.
//
// Run: cd webapp && npx playwright test e2e/help-in-app.spec.ts --project=chromium

const HERE = dirname(fileURLToPath(import.meta.url));
const CONTENT_PATH = resolve(HERE, '../src/help/content.json');

interface Article {
  slug: string;
  title: string;
  summary: string;
  related: string[];
  video?: { file: string };
  poster?: string;
}
interface Content {
  articles: { en: Article[] };
}

const content: Content | null = existsSync(CONTENT_PATH)
  ? (JSON.parse(readFileSync(CONTENT_PATH, 'utf8')) as Content)
  : null;
const en = content?.articles.en ?? [];
const bySlug = (slug: string): Article | undefined => en.find((a) => a.slug === slug);

// Pick an article with a video and at least one related article that exists.
const article = en.find(
  (a) => a.video && a.poster && a.related.some((slug) => bySlug(slug) !== undefined)
);
const relatedArticle = article
  ? bySlug(article.related.find((slug) => bySlug(slug) !== undefined) as string)
  : undefined;

test.skip(!article || !relatedArticle, 'src/help/content.json is absent or has no usable article');

const MEDIA_PATH = '**/storage/v1/object/public/help-videos/**';

test.use({ viewport: { width: 1280, height: 900 } });

test.describe('in-app help (signed in)', () => {
  test('help -> search -> article with video -> related article', async ({ page }, testInfo) => {
    const a = article!;
    const related = relatedArticle!;
    // Hold media requests: the element stays mounted so its attributes can be read.
    await page.route(MEDIA_PATH, () => undefined);

    await page.goto('/circles', { waitUntil: 'domcontentloaded' });
    // Open Help from the account menu (the existing entry point).
    await page.getByRole('button', { name: 'Account' }).click();
    await page.getByRole('menuitem', { name: 'Help' }).click();
    await expect(page).toHaveURL(/\/help$/);
    await expect(page.getByRole('searchbox', { name: 'Search help' })).toBeVisible();
    await expect(page.getByRole('heading', { level: 2, name: 'Popular' })).toBeVisible();
    await checkA11y(page, '/help', testInfo, { wcag22: true });

    // Search by the article title.
    await page.getByRole('searchbox', { name: 'Search help' }).fill(a.title);
    await expect(page.getByRole('status').filter({ hasText: /^Results: \d+$/ })).toBeVisible();
    await page
      .getByRole('list', { name: 'Results' })
      .getByRole('link', { name: new RegExp(a.title.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')) })
      .first()
      .click();

    // Article.
    await expect(page).toHaveURL(new RegExp(`/help/${a.slug}$`));
    await expect(page.getByRole('heading', { level: 1, name: a.title })).toBeVisible();
    const video = page.locator('video');
    await expect(video).toHaveCount(1);
    await expect(video).toHaveAttribute(
      'src',
      new RegExp(`/storage/v1/object/public/help-videos/${a.video!.file.replace('.', '\\.')}$`)
    );
    await expect(video).toHaveAttribute(
      'poster',
      new RegExp(`/storage/v1/object/public/help-videos/${a.poster!.replace('.', '\\.')}$`)
    );
    expect(
      await video.evaluate((el: HTMLVideoElement) => ({
        muted: el.muted,
        autoplay: el.autoplay,
        controls: el.controls,
        loop: el.loop,
        playsInline: el.hasAttribute('playsinline'),
        preload: el.preload,
      }))
    ).toEqual({
      muted: true,
      autoplay: true,
      controls: true,
      loop: false,
      playsInline: true,
      preload: 'metadata',
    });
    await checkA11y(page, `/help/${a.slug}`, testInfo, { wcag22: true });

    // Related article opens in-app.
    await page
      .getByRole('list', { name: 'Related articles' })
      .getByRole('link', { name: new RegExp(related.title.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')) })
      .first()
      .click();
    await expect(page).toHaveURL(new RegExp(`/help/${related.slug}$`));
    await expect(page.getByRole('heading', { level: 1, name: related.title })).toBeVisible();
  });

  test('a video that cannot load keeps the article and says so', async ({ page }) => {
    await page.route(MEDIA_PATH, (route) => route.abort());
    await page.goto(`/help/${article!.slug}`, { waitUntil: 'domcontentloaded' });
    await expect(page.getByRole('heading', { level: 1, name: article!.title })).toBeVisible();
    await expect(page.getByText('Video unavailable right now')).toBeVisible();
    await expect(page.locator('video')).toHaveCount(0);
    await expect(page.getByRole('heading', { level: 2, name: 'Still need help? Contact us' })).toBeVisible();
  });

  test('the Members page links "How does this work?" to the invite article', async ({
    page,
    circleId,
  }) => {
    test.skip(!bySlug('invite-family'), 'no invite-family article in content.json');
    await page.route(MEDIA_PATH, () => undefined);
    await page.goto(`/circles/${circleId}/members`, { waitUntil: 'domcontentloaded' });
    await page.getByRole('link', { name: 'How does this work?' }).click();
    await expect(page).toHaveURL(/\/help\/invite-family$/);
    await expect(
      page.getByRole('heading', { level: 1, name: bySlug('invite-family')!.title })
    ).toBeVisible();
  });
});

test.describe('in-app help (signed out)', () => {
  test.use({ storageState: { cookies: [], origins: [] } });

  test('the Login help link opens the in-app help, with search and an article', async ({
    page,
  }, testInfo) => {
    await page.route(MEDIA_PATH, () => undefined);
    await page.goto('/login', { waitUntil: 'domcontentloaded' });
    await page.getByRole('link', { name: 'Need help? Visit our support center' }).click();
    await expect(page).toHaveURL(/\/help$/);
    await expect(page.getByRole('searchbox', { name: 'Search help' })).toBeVisible();
    await checkA11y(page, '/help (signed out)', testInfo, { wcag22: true });

    await page.getByRole('searchbox', { name: 'Search help' }).fill(article!.title);
    await page.getByRole('list', { name: 'Results' }).getByRole('link').first().click();
    await expect(page).toHaveURL(/\/help\/[a-z0-9-]+$/);
    await expect(page.locator('video')).toHaveCount(1);
    // Signed out: the brand lockup goes back to the login page.
    await expect(page.getByRole('link', { name: 'CircleCare', exact: true })).toHaveAttribute('href', '/login');
  });
});
